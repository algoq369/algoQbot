// Fonction pour obtenir une citation aléatoire
export function getRandomQuote(category?: keyof typeof sacredQuotes): string {
  if (category && sacredQuotes[category]) {
    const quotes = sacredQuotes[category];
    return quotes[Math.floor(Math.random() * quotes.length)];
  }

  // Citation aléatoire de toutes les catégories
  const allQuotes = Object.values(sacredQuotes).flat();
  return allQuotes[Math.floor(Math.random() * allQuotes.length)];
}

// Fonction pour obtenir une question spirituelle aléatoire
export function getRandomSpiritualQuestion(): string {
  return spiritualQuestions[Math.floor(Math.random() * spiritualQuestions.length)];
}
